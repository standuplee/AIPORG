"""Shared SQLAlchemy declarative base and persistence mixins."""

from datetime import datetime
from uuid import UUID, uuid4

from sqlalchemy import DateTime, String, Uuid, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    """Base metadata registry for the AIPORG 2.0 persistence model."""


class UUIDPrimaryKeyMixin:
    """Provide UUID primary keys that remain usable with SQLite test metadata."""

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, default=uuid4)


class CreatedAtMixin:
    """Record the time an immutable persistence artifact was created."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )


class VersionedRunMixin:
    """Store the version lineage for artifacts generated by a workflow run."""

    run_id: Mapped[UUID] = mapped_column(Uuid, nullable=False)
    input_version: Mapped[str] = mapped_column(String(64), nullable=False)
    output_version: Mapped[str] = mapped_column(String(64), nullable=False)
